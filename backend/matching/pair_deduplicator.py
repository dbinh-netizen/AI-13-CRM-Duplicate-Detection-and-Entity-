"""Pair Deduplication Service for SongNhat CRM Duplicate Detection & Entity Resolution.

Sub-milestone: P2.3.3 - Candidate Generation & Deduplication
Module: backend.matching.pair_deduplicator

Key Responsibilities:
1. Multi-path Pair Consolidation: Consolidates duplicate pair edges discovered by multiple
   blocking strategies (e.g. TAX_ID, PHONE, EMAIL, ADDRESS, NORMALIZED_NAME) into a single
   canonical candidate pair.
2. Lossless Path Retention: Retains 100% of contributing blocking paths without overwriting
   or dropping previous discovery metadata.
3. Canonical Ordering: Guarantees left_source_record_id < right_source_record_id.
4. Self-pair & Cross-pool Elimination: Strictly rejects self-pairs and preserves pool isolation.
5. Deterministic Output: Candidate pairs and their attached blocking paths are sorted
   deterministically for idempotent results across runs.
6. Worker Merge Support: Merges candidate sets from concurrent workers without duplicate emission.
"""

from __future__ import annotations

from typing import Any, Dict, List, Optional, Set, Tuple, Union
from uuid import UUID

from pydantic import BaseModel, ConfigDict, Field

from backend.matching.blocking_engine import (
    BlockingCandidatePair,
    BlockingPath,
    BlockingStrategy,
)


class DeduplicationStats(BaseModel):
    """Auditable metrics produced during candidate pair deduplication."""

    raw_pairs_received: int = 0
    duplicate_pairs_merged: int = 0
    unique_pairs_count: int = 0
    multi_path_pairs_count: int = 0
    path_distribution: Dict[int, int] = Field(
        default_factory=dict,
        description="Number of pairs having exactly K blocking paths (e.g. {1: 100, 2: 50, 3: 10})",
    )
    strategy_breakdown: Dict[str, int] = Field(
        default_factory=dict,
        description="Total contribution counts by strategy name across all deduplicated pairs",
    )


class PairDeduplicator:
    """Stateful, thread-safe deduplicator for candidate pairs generated by multi-path blocking."""

    def __init__(self, entity_pool: str = "ACCOUNT"):
        """
        Initialize the deduplicator.

        :param entity_pool: Target entity pool ("ACCOUNT" or "CONTACT").
        """
        self.entity_pool = entity_pool.upper()
        # Mapping canonical tuple (left_id, right_id) -> BlockingCandidatePair
        self._pairs: Dict[Tuple[str, str], BlockingCandidatePair] = {}
        self._raw_pairs_count: int = 0
        self._duplicate_merge_count: int = 0

    @staticmethod
    def canonical_pair(
        id_a: Union[UUID, str], id_b: Union[UUID, str]
    ) -> Optional[Tuple[str, str]]:
        """
        Normalize pair ordering such that left_id < right_id strictly.
        Returns None if id_a == id_b (self-pair).
        """
        str_a = str(id_a).strip()
        str_b = str(id_b).strip()

        if str_a == str_b:
            return None  # Self-pair forbidden

        if str_a < str_b:
            return str_a, str_b
        return str_b, str_a

    def add_pair(
        self,
        id_a: Union[UUID, str],
        id_b: Union[UUID, str],
        path: BlockingPath,
        entity_type: Optional[str] = None,
        matching_run_id: Optional[Union[UUID, str]] = None,
    ) -> bool:
        """
        Add a candidate pair edge discovered via a blocking path.

        :param id_a: First source record ID.
        :param id_b: Second source record ID.
        :param path: The blocking path that produced this candidate pair.
        :param entity_type: Pool ("ACCOUNT" or "CONTACT"). Must match deduplicator pool.
        :param matching_run_id: Optional matching run ID.
        :return: True if this is a newly created unique pair, False if an existing pair was merged.
        """
        pair_key = self.canonical_pair(id_a, id_b)
        if pair_key is None:
            # Self-pair rejected
            return False

        pool = (entity_type or self.entity_pool).upper()
        if pool != self.entity_pool:
            raise ValueError(
                f"Strict Pool Segregation Violation: Cannot add {pool} pair "
                f"to {self.entity_pool} deduplicator."
            )

        self._raw_pairs_count += 1
        left_id, right_id = pair_key

        if pair_key not in self._pairs:
            candidate = BlockingCandidatePair(
                matching_run_id=matching_run_id,
                left_source_record_id=left_id,
                right_source_record_id=right_id,
                entity_type=pool,
                blocking_paths=[path],
            )
            self._pairs[pair_key] = candidate
            return True
        else:
            self._duplicate_merge_count += 1
            self._pairs[pair_key].add_blocking_path(path)
            return False

    def add_candidate(self, candidate: BlockingCandidatePair) -> bool:
        """Add an already constructed BlockingCandidatePair, merging paths if already present."""
        pair_key = self.canonical_pair(
            candidate.left_source_record_id, candidate.right_source_record_id
        )
        if pair_key is None:
            return False

        if candidate.entity_type.upper() != self.entity_pool:
            raise ValueError(
                f"Strict Pool Segregation Violation: Cannot add {candidate.entity_type} "
                f"candidate to {self.entity_pool} deduplicator."
            )

        self._raw_pairs_count += 1
        left_id, right_id = pair_key

        if pair_key not in self._pairs:
            # Make sure canonical IDs are properly set
            cand = BlockingCandidatePair(
                matching_run_id=candidate.matching_run_id,
                left_source_record_id=left_id,
                right_source_record_id=right_id,
                entity_type=self.entity_pool,
                blocking_paths=list(candidate.blocking_paths),
            )
            self._pairs[pair_key] = cand
            return True
        else:
            self._duplicate_merge_count += 1
            for p in candidate.blocking_paths:
                self._pairs[pair_key].add_blocking_path(p)
            return False

    def merge(self, other: PairDeduplicator) -> None:
        """Merge another PairDeduplicator instance into this one (e.g. from parallel workers)."""
        if other.entity_pool != self.entity_pool:
            raise ValueError(
                f"Cannot merge deduplicators with conflicting pools: "
                f"{self.entity_pool} vs {other.entity_pool}"
            )

        for candidate in other._pairs.values():
            self.add_candidate(candidate)

    def get_unique_pairs(self) -> List[BlockingCandidatePair]:
        """
        Return the deduplicated candidate pairs sorted deterministically
        by (left_source_record_id, right_source_record_id).
        """
        sorted_pairs = sorted(
            self._pairs.values(),
            key=lambda x: (x.left_source_record_id, x.right_source_record_id),
        )
        # Ensure paths within each pair are also sorted
        for pair in sorted_pairs:
            pair.blocking_paths.sort()
        return sorted_pairs

    def count(self) -> int:
        """Return the current number of unique candidate pairs."""
        return len(self._pairs)

    def get_stats(self) -> DeduplicationStats:
        """Compute detailed auditable statistics."""
        stats = DeduplicationStats(
            raw_pairs_received=self._raw_pairs_count,
            duplicate_pairs_merged=self._duplicate_merge_count,
            unique_pairs_count=len(self._pairs),
        )

        for pair in self._pairs.values():
            num_paths = len(pair.blocking_paths)
            stats.path_distribution[num_paths] = (
                stats.path_distribution.get(num_paths, 0) + 1
            )
            if num_paths >= 2:
                stats.multi_path_pairs_count += 1

            for path in pair.blocking_paths:
                strat_str = path.strategy.value
                stats.strategy_breakdown[strat_str] = (
                    stats.strategy_breakdown.get(strat_str, 0) + 1
                )

        return stats

    def clear(self) -> None:
        """Clear all stored pairs and counters."""
        self._pairs.clear()
        self._raw_pairs_count = 0
        self._duplicate_merge_count = 0
